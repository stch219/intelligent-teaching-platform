USE itp_platform;

-- ----------------------------------------------------------------------------
-- 1. 任务表增加截止时间列（预警规则 days_before 的判定基准）
-- ----------------------------------------------------------------------------
ALTER TABLE te_task
    ADD COLUMN deadline DATETIME DEFAULT NULL COMMENT '提交截止时间（三级预警扫描基准）' AFTER tips;

-- ----------------------------------------------------------------------------
-- 1.1 预警记录表增加处置状态列（教师可标记已处置，未处置记录才会重复刷新/推送）
-- ----------------------------------------------------------------------------
ALTER TABLE te_warning_record
    ADD COLUMN resolved TINYINT DEFAULT 0 COMMENT '处置状态（0未处置 1已处置）';

